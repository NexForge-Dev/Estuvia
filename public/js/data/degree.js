export const norm = (s) => String(s || '').normalize('NFD').replace(/[̀-ͯ]/g, '').toUpperCase().replace(/\s+/g, ' ').trim();

// "GRADO EN BIOLOGÍA" → "BIOLOGIA". Títulos antigos (licenciado, diplomado) usam o mesmo nome do curso.
