let current = readStored();
const textSources = new WeakMap();
const attrSources = new WeakMap();
const ATTRS = ['placeholder', 'title', 'aria-label', 'alt'];
const SKIP_TAGS = new Set(['SCRIPT', 'STYLE', 'NOSCRIPT']);

function readStored() {
  try {
    const value = localStorage.getItem(STORAGE_KEY);
    if (LANGUAGES.some((l) => l.code === value)) return value;
  } catch { /* armazenamento indisponível */ }
  return 'pt';
}

function htmlLang(code) {
  return code === 'pt' ? 'pt-BR' : code === 'es' ? 'es' : 'en';
}

export const getLanguage = () => current;
export const locale = () => ({ pt: 'pt-BR', es: 'es-ES', en: 'en-GB' }[current] || 'pt-BR');

function translateSource(text) {
  const source = String(text);
  if (current === 'pt' || !source.trim()) return source;
  const leading = source.match(/^\s*/)[0];
  const trailing = source.match(/\s*$/)[0];
  const core = source.trim();

  const dict = DICT[current];
  if (dict && Object.prototype.hasOwnProperty.call(dict, core)) return leading + dict[core] + trailing;

  for (const p of PATTERNS) {
    const match = core.match(p.re);
    if (match) {
      const fn = p[current];
      if (typeof fn === 'function') return leading + fn(match) + trailing;
    }
  }
  return source;
}

export function t(text) {
  return translateSource(text);
}

function translateTextNode(node) {
  let source = textSources.get(node);
  if (source === undefined) {
    source = node.nodeValue;
    textSources.set(node, source);
  }
  const out = translateSource(source);
  if (node.nodeValue !== out) node.nodeValue = out;
}

function translateAttrs(el) {
  let stored = attrSources.get(el);
  for (const attr of ATTRS) {
    if (!el.hasAttribute(attr)) continue;
    if (!stored) {
      stored = {};
      attrSources.set(el, stored);
    }
    if (stored[attr] === undefined) stored[attr] = el.getAttribute(attr);
    const out = translateSource(stored[attr]);
    if (el.getAttribute(attr) !== out) el.setAttribute(attr, out);
  }
}

function walk(node) {
  if (node.nodeType === 3) {
    translateTextNode(node);
    return;
  }
  if (node.nodeType !== 1) return;
  if (SKIP_TAGS.has(node.tagName)) return;
  if (node.dataset && node.dataset.i18nSkip !== undefined) return;
  translateAttrs(node);
  for (const child of Array.from(node.childNodes)) walk(child);
}

export function translateTree(root) {
  if (!root) return;
  if (root.nodeType === 3) {
    translateTextNode(root);
    return;
  }
  walk(root);
}

let observer = null;

function startObserver() {
  if (observer) return;
  observer = new MutationObserver((records) => {
    for (const record of records) {
      if (record.type !== 'childList') continue;
      for (const node of record.addedNodes) translateTree(node);
    }
  });
  observer.observe(document.documentElement, { childList: true, subtree: true });
}

function syncSwitchers() {
  const label = current === 'en' ? 'Language' : 'Idioma';
  for (const select of document.querySelectorAll('.lang-switch select')) {
    select.value = current;
    select.setAttribute('aria-label', label);
  }
}

const baseTitle = typeof document !== 'undefined' ? document.title : '';
const headMeta = [];
if (typeof document !== 'undefined') {
  for (const el of document.querySelectorAll('meta[name="description"], meta[property="og:title"], meta[property="og:description"]')) {
    headMeta.push([el, el.getAttribute('content') || '']);
  }
}

function applyHead() {
  if (baseTitle) document.title = translateSource(baseTitle);
  const ogLocale = { pt: 'pt_BR', es: 'es_ES', en: 'en_GB' }[current];
  for (const [el, source] of headMeta) el.setAttribute('content', translateSource(source));
  const og = document.querySelector('meta[property="og:locale"]');
  if (og && ogLocale) og.setAttribute('content', ogLocale);
}

export function initI18n() {
  document.documentElement.lang = htmlLang(current);
  document.documentElement.dataset.lang = current;
  applyHead();
  translateTree(document.body || document.documentElement);
  syncSwitchers();
  startObserver();
}

export function setLanguage(code) {
  if (!LANGUAGES.some((l) => l.code === code) || code === current) {
    syncSwitchers();
    return;
  }
  current = code;
  try { localStorage.setItem(STORAGE_KEY, code); } catch { /* ignora */ }
  document.documentElement.lang = htmlLang(current);
  document.documentElement.dataset.lang = current;
  applyHead();
  translateTree(document.body || document.documentElement);
  syncSwitchers();
  dispatchEvent(new CustomEvent('estuvia:languagechange', { detail: { language: code } }));
}

